export type TextKey = keyof typeof strings;
export function useI18n() {
  const language = usePreferences((s) => s.language);
  return {
    language,
    t: (key: TextKey) => strings[key][language === "en" ? 0 : 1],
  };
}
export function priceLabel(price: number, language: "en" | "bn") {
  return price === 0
    ? language === "en"
      ? "Free"
      : "বিনামূল্যে"
    : `৳${new Intl.NumberFormat(language === "bn" ? "bn-BD" : "en-BD").format(price)}`;
}
